#!/usr/bin/env python3
"""
Generates mosaic-runtime's table of how many terminal columns each code point occupies.

    ./scripts/generate-code-point-width.py

Wide (2 columns): East_Asian_Width of W or F, including the unassigned code points which
UAX #11 defaults to W. Zero width: nonspacing and enclosing marks, format characters (except the
soft hyphen), and Hangul medial vowels and final consonants which combine with the preceding
syllable. Everything else, including East_Asian_Width A (ambiguous), is one column wide, as in
most terminals.
"""

import pathlib
import re
import urllib.request

UNICODE_VERSION = "18.0.0"
UCD = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd"
OUTPUT = (
	pathlib.Path(__file__).resolve().parent.parent
	/ "mosaic-runtime/src/commonMain/kotlin/org/unitedsoftware/mosaic/text/codePointWidths.kt"
)

# https://www.unicode.org/reports/tr11/#Unassigned
DEFAULT_WIDE = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]
HANGUL_JAMO_JUNGSEONG_JONGSEONG = [(0x1160, 0x11FF), (0xD7B0, 0xD7FF)]
SOFT_HYPHEN = 0x00AD


def ucd_ranges(path, wanted):
	text = urllib.request.urlopen(f"{UCD}/{path}").read().decode()
	ranges = []
	for line in text.splitlines():
		line = line.split("#", 1)[0].strip()
		if not line:
			continue
		code_points, value = (part.strip() for part in line.split(";"))
		if value not in wanted:
			continue
		first, _, last = code_points.partition("..")
		ranges.append((int(first, 16), int(last or first, 16)))
	return ranges


def merge(ranges):
	merged = []
	for first, last in sorted(ranges):
		if merged and first <= merged[-1][1] + 1:
			merged[-1] = (merged[-1][0], max(merged[-1][1], last))
		else:
			merged.append((first, last))
	return merged


def subtract(ranges, code_point):
	result = []
	for first, last in ranges:
		if first <= code_point <= last:
			if first < code_point:
				result.append((first, code_point - 1))
			if code_point < last:
				result.append((code_point + 1, last))
		else:
			result.append((first, last))
	return result


def kotlin_array(name, ranges):
	values = [f"0x{value:X}" for first, last in ranges for value in (first, last)]
	lines = []
	for start in range(0, len(values), 8):
		lines.append("\t" + ", ".join(values[start:start + 8]) + ",")
	body = "\n".join(lines)
	return f"internal val {name}: IntArray = intArrayOf(\n{body}\n)\n"


wide = merge(ucd_ranges("EastAsianWidth.txt", {"W", "F"}) + DEFAULT_WIDE)
zero = merge(
	subtract(ucd_ranges("extracted/DerivedGeneralCategory.txt", {"Mn", "Me", "Cf"}), SOFT_HYPHEN)
	+ HANGUL_JAMO_JUNGSEONG_JONGSEONG
)

OUTPUT.write_text(
	f"""// Generated by scripts/generate-code-point-width.py from Unicode {UNICODE_VERSION}. Do not edit.
@file:Suppress("ktlint")

package org.unitedsoftware.mosaic.text

/** Inclusive ranges, as pairs of first and last code point, of code points two columns wide. */
{kotlin_array("wideCodePointRanges", wide)}
/** Inclusive ranges, as pairs of first and last code point, of code points zero columns wide. */
{kotlin_array("zeroWidthCodePointRanges", zero)}"""
)
print(f"Wrote {len(wide)} wide and {len(zero)} zero width ranges to {OUTPUT}")
